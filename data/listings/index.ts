/**
 * Реестр разделов каталога, для которых уже есть реальные товары с эталонного сайта —
 * ключ это полный путь узла в data/catalog-tree.ts (любой глубины), то же значение,
 * что резолвит app/catalog/[...path]. Отсутствие узла в этом реестре — это не ошибка,
 * а нормальное "для этого терминального узла товары ещё не собраны".
 */
export const catalogListingsByKey: Record<string, CatalogListingData> = Object.fromEntries(
  listings.map((listing) => [listing.path, listing])
);

export function getCatalogListingByPath(path: string): CatalogListingData | undefined {
  return catalogListingsByKey[path];
}

export function findProductInListingByPath(path: string, productId: string) {
  const listing = getCatalogListingByPath(path);
  const product = listing?.products.find((p) => p.id === productId);
  if (!listing || !product) return undefined;
  return { listing, product };
}
