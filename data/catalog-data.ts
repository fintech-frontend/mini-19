export function getCategory(slug: string): CatalogCategory | undefined {
  return catalogCategories.find((c) => c.slug === slug);
}

export function getSubcategory(
  categorySlug: string,
  subcategorySlug: string
): { category: CatalogCategory; subcategory: CatalogSubcategory } | undefined {
  const category = getCategory(categorySlug);
  const subcategory = category?.subcategories.find((s) => s.slug === subcategorySlug);
  if (!category || !subcategory) return undefined;
  return { category, subcategory };
}
