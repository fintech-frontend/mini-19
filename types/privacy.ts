/**
 * Типы страницы «Политика конфиденциальности» (/privacy-policy).
 *
 * Это "UI-типы": именно их ожидает компонент страницы. Когда появится
 * эндпоинт с текстом документа, маппинг «ответ backend → тип отсюда» пишется
 * один раз в lib/api/privacy.ts, а разметку трогать не придётся.
 */

/**
 * Блок текста документа. В оригинале разметка плоская: абзацы это <p>, а
 * заголовки разделов — <p><strong>, отдельных <h2>/<h3> там нет.
 */
export type PrivacyBlock =
  /** Заголовок раздела: «1. ТЕРМИНЫ И ОПРЕДЕЛЕНИЯ». */
  | { type: "heading"; text: string }
  | { type: "paragraph"; text: string };

/** Всё содержимое страницы одним объектом. */
export interface PrivacyPageContent {
  /** Заголовок H1 и последняя хлебная крошка. */
  title: string;
  blocks: PrivacyBlock[];
}
